  // ─────────────────────────────────────────────────────────────
  // MANUAL_BASIC
  // 위치: manuals.js → POST /:storeId/basic
  // 역할: 긴 텍스트를 첫 출근자용 기초 매뉴얼로 정리
  // 입력: bizType, categoryList, chunk (2000자 단위 분할 텍스트)
  // 출력: JSON { category, title, items: [{title, content}] }
